// Generates src/types/api.generated.ts from the server's OpenAPI document (springdoc).
//   pnpm run api:types                  fetch http://localhost:9858/v3/api-docs and rewrite the file
//   pnpm run api:types -- <url|file>    use another spec location
//   pnpm run api:types -- --check       fail when the committed file is stale (for CI)
// Start the backend first: ./gradlew :boot:bootRun (the dev profile; prod switches /v3/api-docs off)
import fs from 'fs';
import path from 'path';
import openapiTS, { astToString } from 'openapi-typescript';

const args = process.argv.slice(2);
const check = args.includes('--check');
const source =
  args.find((a) => !a.startsWith('--')) ?? 'http://localhost:9858/v3/api-docs';
const target = path.resolve(
  import.meta.dirname,
  '../src/types/api.generated.ts'
);

const spec = /^https?:/.test(source)
  ? await (await fetch(source)).json()
  : JSON.parse(fs.readFileSync(source, 'utf8'));
// The server URL depends on where the spec was fetched from and would make the output unstable.
delete spec.servers;

const header = `// SPDX-License-Identifier: Apache-2.0
// SPDX-FileCopyrightText: 2026 Infenia Private Limited

// Generated by scripts/generate-api-types.mjs from the server's /v3/api-docs. Do not edit.
`;
const generated = header + astToString(await openapiTS(spec));

if (check) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
    console.error(
      'src/types/api.generated.ts is stale; run `pnpm run api:types` and commit it.'
    );
    process.exit(1);
  }
  console.log('API types are up to date');
} else {
  fs.writeFileSync(target, generated);
  console.log(`Wrote ${path.relative(process.cwd(), target)}`);
}
